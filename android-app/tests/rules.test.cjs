const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const context = vm.createContext({})
vm.runInContext(fs.readFileSync('app/src/main/assets/rules.js', 'utf8'), context)
const r = context.CourtRules
assert.equal(r.DRILLS.length, 11)
assert.equal(r.sessionXp('free_throw', 20, { attempts: 20, makes: 10, reps: 0 }), 51)
assert.equal(r.sessionXp('conditioning', 240, { attempts: 0, makes: 0, reps: 0 }), 220)
const allocation = r.allocateDailyXp([{id: 1,date: '2026-11-01',raw: 220},{id: 2,date: '2026-11-01',raw: 220},{id: 3,date: '2026-11-02',raw: 220}])
assert.equal(allocation.get(2), 180)
assert.equal(allocation.get(3), 220)
assert.equal(r.careerState(120).level, 2)
const invalid = r.validateTraining({drillId:'free_throw',date:'2026-11-01',durationMin:20,rpe:5,sets:[{attempts:10,makes:11}]},'2026-11-01')
assert.ok(invalid.some(x=>x.includes('命中次数不能超过出手次数')))
console.log('训练项目、XP 上限、升级和成绩校验通过')
